const shebang = {
  label: "a bash shebang",
  pattern: /^#!\s*(?:\/bin\/bash|\/usr\/bin\/env\s+bash)/m,
};
const has = (label, pattern) => ({ label, pattern });

function task(id, title, filename, instruction, solution, rules, explanation) {
  return {
    id,
    title,
    filename,
    instruction,
    starter: "#!/bin/bash\n\n",
    solution,
    rules: [shebang, ...rules],
    explanation,
  };
}

