function lowerFirst(text) {
  return text.charAt(0).toLowerCase() + text.slice(1);
}

function finalizeEntry(entry) {
  const commonFlags = entry.commonFlags || [];
  const keyTerms = entry.keyTerms || [];
  const commonFields = commonFlags.length
    ? commonFlags.map((row) => row.flag)
    : keyTerms.map((row) => row.term);

  return {
    ...entry,
    topic: entry.command,
    description: entry.basicExplanation,
    commonSyntax: entry.syntax,
    commonFlags,
    keyTerms,
    commonFields,
    gotchas: entry.gotchas || [],
    analogy: entry.analogy || null,
    realWorldExample: entry.realWorldExample || null,
    relatedConcepts: entry.relatedCommands,
    fullMeaning: entry.fullMeaning,
  };
}

