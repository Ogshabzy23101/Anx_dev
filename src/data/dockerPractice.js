const has = (label, pattern) => ({ label, pattern });

function task(id, title, filename, instruction, solution, rules, explanation) {
  return {
    id,
    title,
    filename,
    instruction,
    starter: "",
    solution,
    rules,
    explanation,
  };
}

const yamlService = (name) => has(`service: ${name}`, new RegExp(`^\\s{2}${name}:\\s*$`, "m"));

